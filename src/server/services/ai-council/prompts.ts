/**
 * 分析タイプから出力形式を取得
 */
export function getOutputFormatForType(analysisType: string): string {
  switch (analysisType) {
    case "comprehensive":
      return OUTPUT_FORMAT_COMPREHENSIVE;
    case "pricing":
      return OUTPUT_FORMAT_PRICING;
    case "campaign":
      return OUTPUT_FORMAT_CAMPAIGN;
    case "new-treatment":
      return OUTPUT_FORMAT_NEW_TREATMENT;
    default:
      return OUTPUT_FORMAT_COMPREHENSIVE;
  }
}

/**
 * 分析タイプの表示名
 */
export function getQueryForAnalysisType(analysisType: string): string {
  switch (analysisType) {
    case "comprehensive":
      return "当院の経営状況を総合的に分析し、戦略を提案してください";
    case "pricing":
      return "当院の価格設定を分析し、最適な価格を提案してください";
    case "campaign":
      return "当院に効果的なキャンペーン案を提案してください";
    case "new-treatment":
      return "当院に導入すべき新施術を提案してください";
    default:
      return "戦略分析を行ってください";
  }
}

